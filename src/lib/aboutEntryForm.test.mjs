import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const module={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/aboutEntryForm.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{module,exports:module.exports});
const {createAboutEntry,nextAboutEntryOrder,validateAboutEntries,highlightsToText,textToHighlights}=module.exports;
const entry=createAboutEntry(11);
for(const field of ['title','meta','period','description'])assert.equal(entry[field],'','Examples must not become saved input.');
assert.equal(entry.category,'项目经历');
assert.equal(entry.descriptionLabel,'项目描述');
assert.equal(entry.highlightsLabel,'项目亮点');
assert.equal(entry.techStack.length,0);
assert.equal(entry.highlights.length,0);
assert.equal(entry.sortOrder,11);
entry.techStack.push('Actual user data');
assert.equal(createAboutEntry(12).techStack.length,0,'New records must not share mutable arrays.');
assert.equal(nextAboutEntryOrder([{sortOrder:3},{sortOrder:10}]),11);
assert.equal(nextAboutEntryOrder([]),1);
assert.match(validateAboutEntries([entry]),/尚未填写标题/);
entry.title='真实项目';
assert.equal(validateAboutEntries([entry]),'');
const text='没有冒号\n标题：\n：只有文字\nhttps://example.com\n\n  普通亮点  ';
assert.equal(highlightsToText(textToHighlights(text)),'没有冒号\n标题：\n：只有文字\nhttps://example.com\n普通亮点');
assert.equal(textToHighlights(' \n ').length,0);
assert.equal(highlightsToText([{title:'原有标题',detail:'保留说明'},{title:'普通文字',detail:''}]),'原有标题：保留说明\n普通文字');
